//! `problems-docs`: the problem catalog, `docs/problems.md`, rendered from `davhaven_wire::ProblemCode`.
//!
//! The catalog is data of the wire crate, which this tool links already for the contract documents, so the page is
//! rendered in process: one row per code in catalog order, with the text of the variant's doc comment as "when it
//! happens".

use davhaven_wire::ProblemCode;

/// The page, as committed.
pub(crate) fn render() -> String {
    render_rows(ProblemCode::ALL)
}

/// The page for `codes`.
fn render_rows(codes: &[ProblemCode]) -> String {
    let mut page = String::from(
        "# Problem catalog

<!-- Generated by `cargo xtask problems-docs` from `davhaven_wire::ProblemCode` (`crates/wire/src/problem.rs`). Do not edit by hand. -->

Every failure a client can see is one row of this catalog. The management API answers with an RFC 9457 problem document \
(`application/problem+json`) whose `type` is the URN of the row, whose `title` is its title and whose `code` is its code; \
MCP tool results carry the same document. The web pages and the feeds use the HTTP status of the row. A DAV client \
receives the DAV status of the row and, where the row has one, its precondition element in a `DAV:error` body. See \
[`api.md`](api.md#errors) for the document and [`interop.md`](interop.md) for the DAV side.

`code` is stable and the thing to branch on; `title` is the same for every occurrence, while `detail` and \
`errors[].message` are for people and may change. New rows are added over time: clients treat an unknown code like the \
generic problem of its HTTP status. Internal error text never reaches a client.

## Codes

| Code | HTTP | Type | Title | When it happens |
| --- | --- | --- | --- | --- |
",
    );
    page.extend(codes.iter().map(|code| {
        format!(
            "| `{}` | {} | `{}` | {} | {} |\n",
            code.code(),
            code.http_status(),
            code.type_uri(),
            cell(code.title()),
            cell(&code.description()),
        )
    }));
    page.push_str(
        "
## Protocol forms

The DAV status differs from the HTTP status where the WebDAV and CalDAV RFCs prescribe another answer (most \
preconditions are 403 with their element). An MCP client may repeat a call whose problem is retryable later; the tool \
result says so.

| Code | DAV status | DAV element | MCP retryable |
| --- | --- | --- | --- |
",
    );
    page.extend(codes.iter().map(|code| {
        let element = code
            .dav_element()
            .map_or_else(String::new, |element| format!("`{element}`"));
        let retryable = if code.retryable() { "yes" } else { "no" };
        format!(
            "| `{}` | {} | {element} | {retryable} |\n",
            code.code(),
            code.dav_status()
        )
    }));
    page
}

/// `text` as the content of a table cell: a `|` would end the cell.
fn cell(text: &str) -> String {
    text.replace('|', "\\|")
}

#[cfg(test)]
mod tests {
    use super::*;

    /// The table rows of the section that starts with `heading`.
    fn rows<'a>(page: &'a str, heading: &str) -> Vec<&'a str> {
        let section = page.split(heading).nth(1).unwrap();
        let section = section.split("\n## ").next().unwrap();
        section.lines().filter(|line| line.starts_with("| `")).collect()
    }

    #[test]
    fn every_code_has_one_row_in_each_table_in_catalog_order() {
        let page = render();
        for heading in ["## Codes", "## Protocol forms"] {
            let codes: Vec<&str> = rows(&page, heading)
                .iter()
                .map(|row| row.split('`').nth(1).unwrap())
                .collect();
            let expected: Vec<&str> = ProblemCode::ALL.iter().map(|code| code.code()).collect();
            assert_eq!(codes, expected, "{heading}");
        }
    }

    #[test]
    fn a_row_holds_the_status_the_urn_the_title_and_when_it_happens() {
        let page = render_rows(&[ProblemCode::UidConflict]);
        assert_eq!(
            rows(&page, "## Codes"),
            vec![
                "| `uid-conflict` | 409 | `urn:davhaven:problem:uid-conflict` | UID already in use | Another object of \
                 the calendar has the UID (`CALDAV:no-uid-conflict`). |"
            ]
        );
        assert_eq!(
            rows(&page, "## Protocol forms"),
            vec!["| `uid-conflict` | 403 | `CALDAV:no-uid-conflict` | no |"]
        );
    }

    #[test]
    fn a_row_without_an_element_leaves_the_cell_empty_and_says_whether_to_retry() {
        let page = render_rows(&[ProblemCode::Unavailable]);
        assert_eq!(
            rows(&page, "## Protocol forms"),
            vec!["| `unavailable` | 503 |  | yes |"]
        );
    }

    #[test]
    fn every_row_has_the_columns_of_its_table() {
        let page = render();
        for (heading, columns) in [("## Codes", 5), ("## Protocol forms", 4)] {
            for row in rows(&page, heading) {
                let cells = row.replace("\\|", "").matches('|').count() - 1;
                assert_eq!(cells, columns, "{row}");
            }
        }
    }

    #[test]
    fn a_pipe_in_a_cell_is_escaped() {
        assert_eq!(cell("a | b"), "a \\| b");
    }

    #[test]
    fn the_page_ends_with_one_newline() {
        let page = render();
        assert!(page.ends_with("|\n") && !page.ends_with("\n\n"));
    }
}
